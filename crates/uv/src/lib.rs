fn check_pspf_payload() -> Option<(PspFileFooterV1, PathBuf)> {
    let current_exe_path = match std::env::current_exe() {
        Ok(path) => path,
        Err(e) => {
            debug!("Failed to get current executable path: {}", e);
            return None;
        }
    };

    let mut file = match File::open(&current_exe_path) {
        Ok(f) => f,
        Err(e) => {
            debug!("Failed to open current executable '{}': {}", current_exe_path.display(), e);
            return None;
        }
    };

    let file_size = match file.metadata() {
        Ok(meta) => meta.len(),
        Err(e) => {
            debug!("Failed to get metadata for current executable '{}': {}", current_exe_path.display(), e);
            return None;
        }
    };

    // Check if file is large enough to contain magic string and footer
    if file_size < (PSPF_EOF_MAGIC_STRING.len() + PspFileFooterV1::SIZE) as u64 {
        return None;
    }

    // Read magic string
    let magic_string_offset = file_size - PSPF_EOF_MAGIC_STRING.len() as u64;
    if file.seek(SeekFrom::Start(magic_string_offset)).is_err() {
        return None;
    }
    let mut magic_buffer = [0u8; PSPF_EOF_MAGIC_STRING.len()];
    if file.read_exact(&mut magic_buffer).is_err() {
        return None;
    }

    if magic_buffer != *PSPF_EOF_MAGIC_STRING {
        return None; // Not a PSPF file
    }

    // Read footer
    let footer_offset = file_size - (PSPF_EOF_MAGIC_STRING.len() + PspFileFooterV1::SIZE) as u64;
    if file.seek(SeekFrom::Start(footer_offset)).is_err() {
        return None;
    }

    match PspFileFooterV1::read_from(&mut file) {
        Ok(footer) => {
            if footer.version == CURRENT_PSPF_VERSION && footer.verify_checksum() {
                // Further sanity checks on offsets and sizes could be done here
                // e.g., footer.metadata_offset == footer.uv_binary_size
                // footer.payload_offset == footer.metadata_offset + footer.metadata_size
                // etc.
                // And ensure all these offsets/sizes are within file_size bounds.
                let end_of_signature = footer.signature_offset + footer.signature_size;
                if end_of_signature == footer_offset { // Check if signature ends where footer begins
                    Some((footer, current_exe_path))
                } else {
                    debug!("PSPF footer size/offset mismatch with file structure.");
                    None
                }
            } else {
                debug!("PSPF footer version or checksum mismatch. Version: {}, Checksum valid: {}", footer.version, footer.verify_checksum());
                None
            }
        }
        Err(e) => {
            debug!("Failed to read PSPF footer: {}", e);
            None
        }
    }
}


#[allow(unsafe_code)]
pub unsafe fn main<I, T>(args: I) -> ExitCode
where
    I: IntoIterator<Item = T>,
    T: Into<OsString> + Clone,
{
    // PSPF Startup Detection
    if let Some((footer, exe_path)) = check_pspf_payload() {
        // Found a PSPF payload. Switch to execution mode.
        // We need a separate runtime for this, or integrate into the existing one carefully.
        // For now, let's keep it simple and run it, then exit.
        let runtime = tokio::runtime::Builder::new_current_thread()
            .enable_all()
            .build()
            .expect("Failed building the Runtime for PSPF execution");

        match runtime.block_on(execute_pspf_package(&exe_path, footer)) {
            Ok(exit_status) => return exit_status.into(),
            Err(err) => {
                eprintln!("{}: {}", "error".red().bold(), err);
                return ExitStatus::Error.into();
            }
        }
    }

    // Proceed with normal CLI execution if no PSPF payload is detected
    main_internal(args)
}


#[allow(unsafe_code)]
unsafe fn main_internal<I, T>(args: I) -> ExitCode
where
    I: IntoIterator<Item = T>,
    T: Into<OsString> + Clone,
{
    // Set the `UV` variable to the current executable so it is implicitly propagated to all child
    // processes, e.g., in `uv run`.
    if let Ok(current_exe) = std::env::current_exe() {
        // SAFETY: The proof obligation must be satisfied by the caller.
        unsafe {
            // This will become unsafe in Rust 2024
            // See https://doc.rust-lang.org/std/env/fn.set_var.html#safety
            std::env::set_var(EnvVars::UV, current_exe);
        }
    }

    // `std::env::args` is not `Send` so we parse before passing to our runtime
    // https://github.com/rust-lang/rust/pull/48005
    let cli = match Cli::try_parse_from(args) {
        Ok(cli) => cli,
        Err(mut err) => {
            if let Some(ContextValue::String(subcommand)) = err.get(ContextKind::InvalidSubcommand)
            {
                match subcommand.as_str() {
                    "compile" => {
                        err.insert(
                            ContextKind::SuggestedSubcommand,
                            ContextValue::String("uv pip compile".to_string()),
                        );
                    }
                    "install" => {
                        err.insert(
                            ContextKind::SuggestedSubcommand,
                            ContextValue::String("uv pip install".to_string()),
                        );
                    }
                    "uninstall" => {
                        err.insert(
                            ContextKind::SuggestedSubcommand,
                            ContextValue::String("uv pip uninstall".to_string()),
                        );
                    }
                    "freeze" => {
                        err.insert(
                            ContextKind::SuggestedSubcommand,
                            ContextValue::String("uv pip freeze".to_string()),
                        );
                    }
                    "list" => {
                        err.insert(
                            ContextKind::SuggestedSubcommand,
                            ContextValue::String("uv pip list".to_string()),
                        );
                    }
                    "show" => {
                        err.insert(
                            ContextKind::SuggestedSubcommand,
                            ContextValue::String("uv pip show".to_string()),
                        );
                    }
                    _ => {}
                }
            }
            err.exit()
        }
    };

    // See `min_stack_size` doc comment about `main2`
    let min_stack_size = min_stack_size();
    let main2 = move || {
        let runtime = tokio::runtime::Builder::new_current_thread()
            .enable_all()
            .thread_stack_size(min_stack_size)
            .build()
            .expect("Failed building the Runtime");
        // Box the large main future to avoid stack overflows.
        let result = runtime.block_on(Box::pin(run_command_cli(cli)));
        // Avoid waiting for pending tasks to complete.
        //
        // The resolver may have kicked off HTTP requests during resolution that
        // turned out to be unnecessary. Waiting for those to complete can cause
        // the CLI to hang before exiting.
        runtime.shutdown_background();
        result
    };
    let result = std::thread::Builder::new()
        .name("main2".to_owned())
        .stack_size(min_stack_size)
        .spawn(main2)
        .expect("Tokio executor failed, was there a panic?")
        .join()
        .expect("Tokio executor failed, was there a panic?");

    match result {
        Ok(code) => code.into(),
        Err(err) => {
            let mut causes = err.chain();
            eprintln!(
                "{}: {}",
                "error".red().bold(),
                causes.next().unwrap().to_string().trim()
            );
            for err in causes {
                eprintln!("  {}: {}", "Caused by".red().bold(), err.to_string().trim());
            }
            ExitStatus::Error.into()
        }
    }
}
